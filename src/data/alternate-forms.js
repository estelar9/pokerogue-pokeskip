/**
 * Tente de résoudre le nom d'une forme alternative spécifique.
 * @param {number} speciesId - ID de l'espèce nationale
 * @param {number} formIndex - Index de la forme dans PokéRogue
 * @param {string} [formKey] - Clé de la forme PokéRogue (optionnelle)
 * @param {boolean} [isFr=true] - Si la langue demandée est le français
 * @returns {string|null} Le label de la forme (ex: "Danse" ou "Pirouette"), ou null
 */
export function getAlternateFormLabel(speciesId, formIndex, formKey = '', isFr = true) {
  const sid = Number(speciesId);
  const fIdx = Number(formIndex);

  // 1. Recherche directe par (speciesId, formIndex)
  if (sid && !isNaN(fIdx) && alternateForms[sid] && alternateForms[sid][fIdx]) {
    const entry = alternateForms[sid][fIdx];
    return isFr ? (entry.fr || entry.en) : (entry.en || entry.fr);
  }

  // 2. Recherche par formKey normalisée
  if (formKey && typeof formKey === 'string') {
    const cleanKey = formKey.toUpperCase().trim().replace(/^SPECIESFORMKEY\./, '');
    if (formKeyNames[cleanKey]) {
      const entry = formKeyNames[cleanKey];
      return isFr ? (entry.fr || entry.en) : (entry.en || entry.fr);
    }
  }

  return null;
}
